let fruit = "kiwi";

switch(fruit){
    case "apple":
        console.log("Apple fruit selected");
    case "banana":
        console.log("Banana fruit selected");
    case "kiwi":
        console.log("Kiwi fruit selected");
    case "orange":
        console.log("Orange fruit selected");
    default:
        console.log("NO fruit selected");
}

