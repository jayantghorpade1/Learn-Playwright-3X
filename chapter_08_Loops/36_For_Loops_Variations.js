//Here, we will see how we can pass difference combination of conditions

for(let num = 0; num<10; num++){
    console.log(num); // Will print 0 to 9
}
console.log(" ***** FOR Loop1 Ended *****"); 

for(let num1 = 1; num1<=10; ++num1){
    console.log(num1); // Will print 0 to 10
}
console.log(" ***** FOR Loop2 Ended *****");

for(let num2 = 0; num2<=10; num2++){
    console.log(num2); // Will print 0 to 10
}
console.log(" ***** FOR Loop3 Ended *****");