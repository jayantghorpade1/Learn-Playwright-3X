/**
 * FOR Loop: 
 */

let num = 10;

for(let i = 0; i<=num; i++){
    console.log(i);
}

for(let i=0; i<=num; ++i){
    console.log(i);
}

// Here, in the above example, it won't make any difference if we incerement the value of 'i' in either ways
// pre-increment or post-increment of 'i' will have same value in both the cases